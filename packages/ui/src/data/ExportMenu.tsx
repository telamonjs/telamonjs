/**
 * ExportMenu Component
 *
 * Dropdown menu for exporting table data to Excel, CSV, or PDF
 * with options to export all data, selected rows, or current page.
 */

'use client'

import { useEffect, useRef, useState, type ReactNode } from 'react'
import { useLocale } from 'next-intl'
import { logger } from '../utils/logger'
import { useTelamonjsT } from '../i18n/use-t'
import {
  Download,
  FileSpreadsheet,
  FileText,
  FileImage,
  Loader2,
} from 'lucide-react'
import { Button } from '../ui/button'
import { useHoverPopover } from '../hooks/use-hover-popover'
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuLabel,
  DropdownMenuSeparator,
  DropdownMenuTrigger,
  DropdownMenuSub,
  DropdownMenuSubTrigger,
  DropdownMenuSubContent,
} from '../ui/dropdown-menu'
import { ColumnDef } from '@tanstack/react-table'
// Type-only: exportUtils pulls jspdf/papaparse, loaded on demand in handleExport
import type { PDFExportOptions } from './exportUtils'
import { toast } from 'sonner'

export type ExportFormat = 'excel' | 'csv' | 'pdf'

/** What `ExportMenu.loadAll` receives: the user's Cancel, and a progress reporter. */
export interface ExportLoadAllContext {
  /** Aborted when the user cancels or the menu unmounts */
  signal: AbortSignal
  /** Rows fetched so far, out of `target` — updates the progress toast */
  onProgress: (loaded: number, target: number) => void
}

export interface ExportMenuProps<T> {
  data: T[]
  columns: ColumnDef<T>[]
  selectedRows?: T[]
  currentPageRows?: T[]
  filename?: string
  formats?: ExportFormat[]
  /** Excel sheet name (default: localized "Data"). */
  sheetName?: string
  /** Append `_YYYY-MM-DD` to the filename, once (default `true`). */
  appendDate?: boolean
  pdfOptions?: Omit<
    PDFExportOptions,
    'filename' | 't' | 'locale' | 'sheetName' | 'appendDate'
  >
  /**
   * Custom generator: when present the menu only orchestrates (loading state, toast,
   * callbacks) and the built-in Excel/CSV/PDF generation is skipped.
   */
  onExport?: (
    format: ExportFormat,
    rows: T[],
    columns: ColumnDef<T>[]
  ) => Promise<void> | void
  /**
   * Source of the "All" scope instead of `data` — e.g. every page of a server
   * query (`fetchAllPages`). While it runs, a progress toast offers Cancel
   * (aborting `signal`). Resolve the rows and the server total: fewer rows
   * than `total` (a row cap) shows a warning.
   */
  loadAll?: (ctx: ExportLoadAllContext) => Promise<{ rows: T[]; total: number }>
  /** Count shown next to "All" when `loadAll` is set (the rows matching on the server). */
  allCount?: number
  /**
   * App-side export (e.g. a file generated by the server): the menu lists the
   * formats only — no scopes, no rows — and calls this with the chosen one,
   * pending until it settles. Failures show the export error toast; success is
   * the handler's to announce.
   */
  onServerExport?: (format: ExportFormat) => unknown
  onExportStart?: () => void
  onExportComplete?: () => void
  onExportError?: (error: Error) => void
  disabled?: boolean
  className?: string
  /**
   * Custom trigger (e.g. a "⋯" icon button) — the menu becomes the list's
   * actions menu. Must forward ref/props (asChild).
   */
  trigger?: ReactNode
  /** Extra items above the export section (e.g. "Refresh") */
  children?: ReactNode
}

export function ExportMenu<T>({
  data,
  columns,
  selectedRows = [],
  currentPageRows = [],
  filename = 'export',
  formats = ['excel', 'csv', 'pdf'],
  sheetName,
  appendDate,
  pdfOptions = {},
  onExport,
  loadAll,
  allCount,
  onServerExport,
  onExportStart,
  onExportComplete,
  onExportError,
  disabled = false,
  className,
  trigger,
  children,
}: ExportMenuProps<T>) {
  const t = useTelamonjsT()
  const locale = useLocale()
  const [isExporting, setIsExporting] = useState(false)
  // The running `loadAll`: cancelled from its toast, or when the menu unmounts
  const loadAllRef = useRef<AbortController | null>(null)
  useEffect(() => () => loadAllRef.current?.abort(), [])
  // opens on hover like the other toolbar dropdowns
  const { open, setOpen, triggerProps, contentProps } = useHoverPopover({
    disabled: disabled || isExporting
  })

  /** Rows of `loadAll`, with a progress toast; `null` when the user cancelled. */
  const loadAllRows = async (
    load: NonNullable<typeof loadAll>
  ): Promise<T[] | null> => {
    const controller = new AbortController()
    loadAllRef.current = controller
    const action = { label: t('common.cancel'), onClick: () => controller.abort() }
    const toastId = toast.loading(t('common.loading'), { action })
    try {
      const { rows, total } = await load({
        signal: controller.signal,
        onProgress: (loaded, target) =>
          toast.loading(t('data.exportFetching', { loaded, total: target }), {
            id: toastId,
            action,
          }),
      })
      if (controller.signal.aborted) throw new DOMException('', 'AbortError')
      if (rows.length < total) {
        toast.warning(t('data.exportTruncated', { count: rows.length, total }))
      }
      return rows
    } catch (error) {
      if (!controller.signal.aborted) throw error
      toast.info(t('data.exportCancelled'))
      return null
    } finally {
      toast.dismiss(toastId)
      loadAllRef.current = null
    }
  }

  const handleServerExport = async (
    run: NonNullable<typeof onServerExport>,
    format: ExportFormat
  ) => {
    try {
      setIsExporting(true)
      onExportStart?.()
      await run(format)
      onExportComplete?.()
    } catch (error) {
      logger.error('Export error', {
        error: error instanceof Error ? error : String(error),
      })
      toast.error(t('data.exportError'))
      onExportError?.(error as Error)
    } finally {
      setIsExporting(false)
    }
  }

  const handleExport = async (
    format: ExportFormat,
    scope: 'all' | 'selected' | 'page'
  ) => {
    try {
      setIsExporting(true)
      onExportStart?.()

      // Determine which data to export
      let dataToExport: T[] = data
      let scopeLabel = t('data.scopeAll')

      switch (scope) {
        case 'selected':
          if (selectedRows.length === 0) {
            toast.error(t('data.noRowsSelected'))
            return
          }
          dataToExport = selectedRows
          scopeLabel = t('data.scopeSelected', { count: selectedRows.length })
          break
        case 'page':
          if (currentPageRows.length === 0) {
            toast.error(t('data.noDataCurrentPage'))
            return
          }
          dataToExport = currentPageRows
          scopeLabel = t('data.scopeCurrentPage')
          break
        case 'all':
        default: {
          const rows = loadAll ? await loadAllRows(loadAll) : data
          if (!rows) return // cancelled
          dataToExport = rows
          scopeLabel = t('data.scopeAll')
          break
        }
      }

      if (dataToExport.length === 0) {
        toast.error(t('data.noDataToExport'))
        return
      }

      const label = { excel: 'Excel', csv: 'CSV', pdf: 'PDF' }[format]

      if (onExport) {
        await onExport(format, dataToExport, columns)
        toast.success(
          t('data.exportSuccess', { format: label, scope: scopeLabel })
        )
        onExportComplete?.()
        return
      }

      // Load the heavy export stack only when the user actually exports
      const { exportToExcel, exportToCSV, exportToPDF } = await import(
        './exportUtils'
      )

      // exportUtils appends the date to the filename (once)
      const common = { includeHiddenColumns: false, appendDate, t, locale }
      switch (format) {
        case 'excel':
          await exportToExcel(dataToExport, columns, filename, {
            ...common,
            sheetName,
          })
          break
        case 'csv':
          exportToCSV(dataToExport, columns, filename, common)
          break
        case 'pdf':
          exportToPDF(dataToExport, columns, filename, {
            ...common,
            ...pdfOptions,
            orientation: pdfOptions.orientation || 'landscape',
          })
          break
      }
      toast.success(
        t('data.exportSuccess', { format: label, scope: scopeLabel })
      )

      onExportComplete?.()
    } catch (error) {
      logger.error('Export error', {
        error: error instanceof Error ? error : String(error),
      })
      toast.error(t('data.exportError'))
      onExportError?.(error as Error)
    } finally {
      setIsExporting(false)
    }
  }

  const getFormatIcon = (format: ExportFormat) => {
    switch (format) {
      case 'excel':
        return <FileSpreadsheet className='h-4 w-4 text-green-600' />
      case 'csv':
        return <FileText className='h-4 w-4 text-blue-600' />
      case 'pdf':
        return <FileImage className='h-4 w-4 text-red-600' />
    }
  }

  const getFormatLabel = (format: ExportFormat) => {
    switch (format) {
      case 'excel':
        return t('data.excelFormat')
      case 'csv':
        return t('data.csvFormat')
      case 'pdf':
        return t('data.pdfFormat')
    }
  }

  const allLabelCount = loadAll ? (allCount ?? 0) : data.length
  const hasSelectedRows = selectedRows.length > 0
  const hasCurrentPageRows = currentPageRows.length > 0

  return (
    <DropdownMenu open={open} onOpenChange={setOpen} modal={false}>
      <DropdownMenuTrigger asChild {...triggerProps}>
        {trigger ?? (
          <Button
            variant='outline'
            size='sm'
            className={className}
            disabled={disabled || isExporting}
            data-testid='export-menu-trigger'
          >
            {isExporting ? (
              <Loader2 className='h-4 w-4 animate-spin' />
            ) : (
              <Download className='h-4 w-4' />
            )}
            <span className='ml-1.5'>{t('data.export')}</span>
          </Button>
        )}
      </DropdownMenuTrigger>
      <DropdownMenuContent align='end' className='w-56' {...contentProps}>
        {children && (
          <>
            {children}
            <DropdownMenuSeparator />
          </>
        )}
        <DropdownMenuLabel>{t('data.exportFormatLabel')}</DropdownMenuLabel>
        <DropdownMenuSeparator />

        {onServerExport && formats.map(format => (
          <DropdownMenuItem
            key={format}
            onClick={() => void handleServerExport(onServerExport, format)}
            disabled={isExporting}
          >
            {getFormatIcon(format)}
            <span className='ml-2'>{getFormatLabel(format)}</span>
          </DropdownMenuItem>
        ))}

        {!onServerExport && formats.map(format => (
          <DropdownMenuSub key={format}>
            <DropdownMenuSubTrigger>
              {getFormatIcon(format)}
              <span className='ml-2'>{getFormatLabel(format)}</span>
            </DropdownMenuSubTrigger>
            <DropdownMenuSubContent {...contentProps}>
              <DropdownMenuItem
                onClick={() => handleExport(format, 'all')}
                disabled={isExporting}
              >
                <span className='text-sm'>{t('data.exportAll')}</span>
                {allLabelCount > 0 && (
                  <span className='ml-auto text-xs text-muted-foreground'>
                    {t('data.recordCount', { count: allLabelCount })}
                  </span>
                )}
              </DropdownMenuItem>

              {hasSelectedRows && (
                <DropdownMenuItem
                  onClick={() => handleExport(format, 'selected')}
                  disabled={isExporting}
                >
                  <span className='text-sm'>{t('data.exportSelected')}</span>
                  <span className='ml-auto text-xs text-muted-foreground'>
                    {t('data.recordCount', { count: selectedRows.length })}
                  </span>
                </DropdownMenuItem>
              )}

              {hasCurrentPageRows && (
                <DropdownMenuItem
                  onClick={() => handleExport(format, 'page')}
                  disabled={isExporting}
                >
                  <span className='text-sm'>{t('data.exportCurrentPage')}</span>
                  <span className='ml-auto text-xs text-muted-foreground'>
                    {t('data.recordCount', { count: currentPageRows.length })}
                  </span>
                </DropdownMenuItem>
              )}
            </DropdownMenuSubContent>
          </DropdownMenuSub>
        ))}

        <DropdownMenuSeparator />
        <div className='px-2 py-1.5 text-xs text-muted-foreground'>
          {t('data.filtersAppliedHint')}
        </div>
      </DropdownMenuContent>
    </DropdownMenu>
  )
}
