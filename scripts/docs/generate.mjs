#!/usr/bin/env node
/**
 * Regenerates every docs file derived from the code:
 *   docs/exports.md                              — every entry point of every package, runtime names + types
 *   apps/docs/content/docs/reference/exports.mdx — the same index as a site page
 *   llms.txt                                     — llmstxt.org index (site sections, package READMEs, exports index)
 *   llms-full.txt                                — every site page, title first, MDX plumbing stripped
 *   packages/*\/README.md                         — only between existing `<!-- generated:peers -->` and
 *                                                  `<!-- generated:entries -->` markers (never adds markers)
 *
 * Usage: pnpm docs:generate           (writes the files)
 *        pnpm docs:generate --check   (CI: fails if a file is stale)
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { LIBRARY_PACKAGES, PACKAGES, ROOT, entryPoints, pkgJson, readJson, uiSnapshotNames } from './exports-lib.mjs'

const CHECK = process.argv.includes('--check')
const HEADER = 'Generated by `pnpm docs:generate` — do not edit by hand.'
const REPO_URL = readJson(join(ROOT, 'package.json')).repository.url.replace(/^git\+/, '').replace(/\.git$/, '')
const out = {}

// ── exports: Map<package, [{ spec, runtime[], types[], kind, target }]> ──────
const snapshot = uiSnapshotNames()
const surface = new Map(
  LIBRARY_PACKAGES.map(p => [
    p,
    entryPoints(p).map(e => {
      if (!e.exports) return e
      const runtime = [...e.exports].filter(([, k]) => k === 'runtime').map(([n]) => n)
      const types = [...e.exports].filter(([, k]) => k === 'type').map(([n]) => n)
      if (p === 'ui' && e.entry === '.') {
        // The ui root's runtime set is the snapshot; the collector must agree, or it has a blind spot.
        const missing = [...snapshot].filter(n => !e.exports.has(n))
        const extra = runtime.filter(n => !snapshot.has(n))
        if (missing.length || extra.length) {
          console.error(`✗ export collector disagrees with the ui snapshot — not found: ${missing.join(', ') || '-'}; runtime but not pinned: ${extra.join(', ') || '-'}`)
          process.exit(1)
        }
        return { ...e, runtime: [...snapshot].sort(), types: [...e.exports.keys()].filter(n => !snapshot.has(n)).sort() }
      }
      return { ...e, runtime: runtime.sort(), types: types.sort() }
    }),
  ])
)
const bins = p => Object.keys(pkgJson(p).bin ?? {}).sort()
const nonModule = e => `${e.kind === 'stylesheet' ? 'Stylesheet' : 'File'} \`${e.target}\`, no named exports.`
const code = names => names.map(n => `\`${n}\``).join(' · ')

{
  const md = [`# Public API index\n\n${HEADER}\n\nEvery entry point of every \`@telamonjs/*\` package, with its runtime names and its\n**types** (listed apart, marked \`(type)\`). The ui root's runtime names are pinned by\n\`packages/ui/src/__snapshots__/index.test.ts.snap\`; everything else is read from the\nsource barrels. Names not listed are not public API: do not import, document or assume them.`]
  const mdx = [`---\ntitle: Exports & entry points\ndescription: Every entry point of every package, with its runtime names and its types.\n---\n\n{/* ${HEADER} Source: scripts/docs/generate.mjs */}\n\nEvery entry point of every \`@telamonjs/*\` package. **Runtime** names are values you\ncan import and call; **types** are erased at build time (\`import type\`). Names not\nlisted are not public API.`]
  for (const [p, entries] of surface) {
    md.push(`## @telamonjs/${p}`)
    mdx.push(`## @telamonjs/${p}`)
    for (const e of entries) {
      md.push(`### \`${e.spec}\``)
      mdx.push(`### \`${e.spec}\``)
      if (!e.exports) {
        md.push(nonModule(e))
        mdx.push(nonModule(e))
        continue
      }
      md.push(`Runtime:\n\n${e.runtime.map(n => `- \`${n}\``).join('\n') || '- (none)'}`)
      md.push(`Types:\n\n${e.types.map(n => `- \`${n}\` (type)`).join('\n') || '- (none)'}`)
      mdx.push(`**Runtime:** ${code(e.runtime) || '(none)'}`)
      mdx.push(`**Types:** ${code(e.types) || '(none)'}`)
    }
  }
  const cli = `## @telamonjs/cli\n\nNo library entry points: the package only ships bins. Bins: ${code(bins('cli'))}.`
  out['docs/exports.md'] = [...md, cli].join('\n\n') + '\n'
  out['apps/docs/content/docs/reference/exports.mdx'] = [...mdx, cli].join('\n\n') + '\n'
}

// ── site pages in sidebar order (root meta.json, separators = sections) ─────
const DOCS = join(ROOT, 'apps/docs/content/docs')
const pageFile = slug => [join(DOCS, `${slug}.mdx`), join(DOCS, slug, 'index.mdx')].find(f => existsSync(f))
function folderPages(dir) {
  const meta = existsSync(join(DOCS, dir, 'meta.json')) ? readJson(join(DOCS, dir, 'meta.json')) : { pages: ['...'] }
  return expand(meta.pages, dir)
}
function expand(pages, dir) {
  const files = []
  for (const ref of pages) {
    if (/^---.*---$/.test(ref)) continue
    if (ref === '...') {
      // rest of the folder, alphabetically
      const here = readdirSync(join(DOCS, dir)).filter(f => f.endsWith('.mdx')).map(f => join(DOCS, dir, f)).sort()
      files.push(...here.filter(f => !files.includes(f)))
      continue
    }
    const slug = join(dir, ref.replace(/^\.\.\./, ''))
    const file = pageFile(slug)
    if (file && !ref.startsWith('...')) files.push(file)
    else if (existsSync(join(DOCS, slug)) && statSync(join(DOCS, slug)).isDirectory()) files.push(...folderPages(slug))
  }
  return files
}
const sections = [] // [{ title, files }]
{
  const meta = readJson(join(DOCS, 'meta.json'))
  let current = { title: 'Introduction', refs: [] }
  for (const ref of meta.pages) {
    const sep = ref.match(/^---(.*)---$/)
    if (sep) {
      sections.push(current)
      current = { title: sep[1], refs: [] }
    } else current.refs.push(ref)
  }
  sections.push(current)
  // The generated exports page duplicates docs/exports.md (linked under "API"), and
  // reading it here would make this run depend on the previous one.
  const generated = join(DOCS, 'reference/exports.mdx')
  for (const s of sections) s.files = expand(s.refs, '').filter(f => f !== generated)
}
const seen = new Set([...sections.flatMap(s => s.files), join(DOCS, 'reference/exports.mdx')])
const walk = dir => readdirSync(dir).flatMap(e => (statSync(join(dir, e)).isDirectory() ? walk(join(dir, e)) : [join(dir, e)]))
const orphans = walk(DOCS).filter(f => f.endsWith('.mdx') && !seen.has(f)).sort()
if (orphans.length) sections.push({ title: 'Other pages', files: orphans })

function readPage(file) {
  const src = readFileSync(file, 'utf8')
  const fm = src.match(/^---\n([\s\S]*?)\n---\n/)
  const field = name => fm?.[1].match(new RegExp(`^${name}:\\s*(.*)$`, 'm'))?.[1].trim().replace(/^(['"])(.*)\1$/, '$2')
  // Drop MDX plumbing outside code fences: import lines, <*Preview /> demos and the legacy `# Title` H1.
  let fence = null
  let inImport = false
  const body = []
  for (const line of (fm ? src.slice(fm[0].length) : src).split('\n')) {
    const marker = line.match(/^\s*(```+|~~~+)/)?.[1]
    if (marker && (!fence || marker.startsWith(fence))) fence = fence ? null : marker
    else if (!fence) {
      if (inImport) {
        inImport = !/from\s+['"][^'"]+['"]/.test(line)
        continue
      }
      if (/^import\s/.test(line)) {
        inImport = !/from\s+['"][^'"]+['"]|^import\s+['"]/.test(line)
        continue
      }
      if (/^\s*<\w*Preview\b[^>]*\/>\s*$/.test(line) || /^# /.test(line)) continue
    }
    body.push(line)
  }
  return {
    title: field('title') ?? relative(DOCS, file),
    description: field('description'),
    rel: relative(ROOT, file),
    body: body.join('\n').replace(/\n{3,}/g, '\n\n').trim(),
  }
}

{
  const pages = sections.flatMap(s => s.files).map(readPage)
  out['llms-full.txt'] = `# TelamonJS docs — full text\n\n${HEADER}\nEvery page of the docs site (apps/docs/content/docs) in sidebar order: title, description, source path, then the page body.\n${pages
    .map(pg => `\n\n---\n\n# ${pg.title}\n\n${pg.description ? `> ${pg.description}\n\n` : ''}Source: ${pg.rel}\n\n${pg.body}`)
    .join('')}\n`

  // ponytail: links are repo paths until the site has a public URL; switch them then.
  const pitch = readJson(join(ROOT, 'package.json')).description
  const site = sections
    .filter(s => s.files.length)
    .map(s => `## ${s.title}\n\n${s.files.map(readPage).map(pg => `- [${pg.title}](${pg.rel})${pg.description ? `: ${pg.description}` : ''}`).join('\n')}`)
    .join('\n\n')
  const pkgs = PACKAGES.map(p => `- [@telamonjs/${p}](packages/${p}/README.md): ${p === 'cli' ? 'commands — ' : ''}${pkgJson(p).description}`).join('\n')
  out['llms.txt'] = `# TelamonJS\n\n> ${pitch}\n\n${HEADER}\n\n## Packages\n\n${pkgs}\n\n## API\n\n- [Public API index](docs/exports.md): every entry point of every package, runtime names and types\n- [AGENTS.md](AGENTS.md): how to work in this repository (commands, evidence rule, traps)\n\n${site}\n\n## Optional\n\n- [llms-full.txt](llms-full.txt): every docs page above, concatenated in one file\n- [LICENSE](LICENSE): MIT\n`
}

// ── README marker blocks (content between existing markers only) ────────────
function peersBlock(p) {
  const pj = pkgJson(p)
  const peers = Object.entries(pj.peerDependencies ?? {})
  const optional = name => pj.peerDependenciesMeta?.[name]?.optional === true
  const required = peers.filter(([n]) => !optional(n))
  const lines = []
  if (p !== 'cli') lines.push('```bash', `pnpm add ${[pj.name, ...required.map(([n]) => n)].join(' ')}`, '```', '')
  if (!peers.length) return [...lines, 'No peer dependencies.'].join('\n')
  const row = ([n, range]) => `| \`${n}\`${optional(n) ? ' (optional)' : ''} | \`${range.replaceAll('|', '\\|')}\` |`
  return [...lines, '| Peer dependency | Range |', '| --- | --- |', ...required.map(row), ...peers.filter(([n]) => optional(n)).map(row)].join('\n')
}
function entriesBlock(p) {
  if (p === 'cli') return bins(p).map(b => `- \`${b}\``).join('\n')
  const list = surface.get(p).map(e => `- \`${e.spec}\`${e.exports ? '' : ` (${e.kind === 'stylesheet' ? 'stylesheet' : `file \`${e.target}\``})`}`)
  return [...list, '', `Every name each entry point exports, runtime and types: [Public API index](${REPO_URL}/blob/main/docs/exports.md).`].join('\n')
}
for (const p of PACKAGES) {
  const rel = `packages/${p}/README.md`
  let text = readFileSync(join(ROOT, rel), 'utf8')
  for (const [name, block] of [['peers', peersBlock], ['entries', entriesBlock]]) {
    const re = new RegExp(`(<!-- generated:${name} -->)[\\s\\S]*?(<!-- /generated:${name} -->)`)
    text = text.replace(re, (_, open, close) => `${open}\n${block(p)}\n${close}`)
  }
  out[rel] = text
}

// ── write or check ──────────────────────────────────────────────────────────
const stale = []
for (const [rel, text] of Object.entries(out)) {
  const file = join(ROOT, rel)
  const current = existsSync(file) ? readFileSync(file, 'utf8') : null
  if (current === text) continue
  if (CHECK) stale.push(rel)
  else writeFileSync(file, text)
}
if (stale.length) {
  console.error(`✗ stale generated files: ${stale.join(', ')} — run \`pnpm docs:generate\` and commit`)
  process.exit(1)
}
console.log(CHECK ? '✓ generated docs are up to date' : '✓ generated docs written')
